package staticClasses;

public class A {


    public void run() {
        System.out.println("A run");
    }

    public void scan() {
        System.out.println("A scan");
    }

    public static void print() {
        System.out.println("A print");
    }

    public final void on() {
        System.out.println("A on");
    }

    public static final void off() {
        System.out.println("A on");
    }

}
